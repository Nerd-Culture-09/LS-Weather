/*
 * Builds components/lucide-icon/lucide-icon.acss from lucide-static.
 *
 * Mini programs can't use lucide-react, and <image> can't recolour an SVG,
 * so each icon becomes a CSS mask: the icon's shape cuts out a box whose
 * background-color is the icon colour. Only the icons listed below are
 * included, to keep the package small.
 *
 * To add an icon: put its name (from https://lucide.dev/icons) in ICONS,
 * then run `npm run build:icons`.
 */
const fs = require('fs');
const path = require('path');

const ICONS = [
  // Weather conditions
  'sun', 'moon', 'cloud-sun', 'cloud-moon', 'cloud', 'cloud-fog', 'cloud-drizzle',
  'cloud-rain', 'cloud-rain-wind', 'cloud-hail', 'cloud-snow', 'cloud-sun-rain', 'cloud-moon-rain',
  'cloud-lightning', 'cloud-off', 'thermometer',
  // Weather details
  'droplets', 'wind', 'umbrella', 'sunrise', 'sunset', 'calendar-days', 'arrow-up', 'refresh-cw',
  // Places
  'map-pin', 'locate-fixed', 'history', 'search', 'star',
  // General UI
  'chevron-right', 'chevron-down', 'chevron-up', 'x', 'circle-alert', 'triangle-alert',
];

// Extra variants derived from a Lucide icon
const VARIANTS = {
  'star-filled': { from: 'star', fill: true },
};

const ICON_DIR = path.join(path.dirname(require.resolve('lucide-static/package.json')), 'icons');
const OUT_FILE = path.join(__dirname, '..', 'components', 'lucide-icon', 'lucide-icon.acss');
const VERSION = require('lucide-static/package.json').version;

function readSvg(name, options) {
  const file = path.join(ICON_DIR, name + '.svg');
  if (!fs.existsSync(file)) {
    throw new Error(`Unknown Lucide icon "${name}" (checked ${file})`);
  }

  let svg = fs.readFileSync(file, 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*class="[^"]*"/, '')
    .replace(/\s*width="24"/, '')
    .replace(/\s*height="24"/, '')
    // Masks only use alpha, so any opaque colour works
    .replace(/currentColor/g, '#000');

  if (options && options.fill) {
    svg = svg.replace('fill="none"', 'fill="#000"');
  }

  return svg.replace(/\s+/g, ' ').replace(/> </g, '><').trim();
}

// Compact, CSS-safe data URI (same approach as mini-svg-data-uri)
function toDataUri(svg) {
  const encoded = svg
    .replace(/"/g, "'")
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E');
  return `data:image/svg+xml,${encoded}`;
}

function rule(className, svg) {
  const uri = toDataUri(svg);
  return `.lc-${className} {\n  -webkit-mask-image: url("${uri}");\n  mask-image: url("${uri}");\n}`;
}

const rules = ICONS.map((name) => rule(name, readSvg(name)));
Object.keys(VARIANTS).forEach((name) => {
  const variant = VARIANTS[name];
  rules.push(rule(name, readSvg(variant.from, variant)));
});

const css = `/*
 * GENERATED by scripts/build-icons.js — do not edit by hand.
 * Icons: Lucide v${VERSION} (https://lucide.dev), ISC License.
 */

.lc {
  display: inline-block;
  flex-shrink: 0;
  vertical-align: middle;
  background-color: currentColor;
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-position: center;
  mask-position: center;
  -webkit-mask-size: contain;
  mask-size: contain;
}

${rules.join('\n\n')}
`;

fs.writeFileSync(OUT_FILE, css);
console.log(`Wrote ${rules.length} icons to ${path.relative(process.cwd(), OUT_FILE)} (${(css.length / 1024).toFixed(1)} KB)`);
